import Foundation

/// Korean remains the fallback. macOS chooses the preferred supported app language;
/// all saved IDs, category keys, and usage data stay independent of display text.
enum L10n {
    enum Language: Equatable, Sendable {
        case korean, simplifiedChinese
    }

    static let currentLanguage = language(for: Locale.preferredLanguages)

    static func language(for preferences: [String]) -> Language {
        for preference in preferences {
            let tag = preference.replacingOccurrences(of: "_", with: "-").lowercased()
            if tag == "ko" || tag.hasPrefix("ko-") { return .korean }
            if tag == "zh" || tag == "zh-cn" || tag == "zh-sg" || tag.hasPrefix("zh-hans") {
                return .simplifiedChinese
            }
        }
        return .korean
    }

    /// Preserve an interpolation's template separately from its values. For example,
    /// "다음 선물까지 \(days)일" looks up "다음 선물까지 {0}일" rather than each day's number.
    struct Message: ExpressibleByStringLiteral, ExpressibleByStringInterpolation {
        var template: String
        var arguments: [String]

        init(stringLiteral value: String) {
            template = value
            arguments = []
        }

        init(stringInterpolation value: StringInterpolation) {
            template = value.template
            arguments = value.arguments
        }

        struct StringInterpolation: StringInterpolationProtocol {
            var template = ""
            var arguments: [String] = []

            init(literalCapacity: Int, interpolationCount: Int) {
                template.reserveCapacity(literalCapacity)
                arguments.reserveCapacity(interpolationCount)
            }

            mutating func appendLiteral(_ literal: String) { template += literal }

            mutating func appendInterpolation<T>(_ value: T) {
                template += "{\(arguments.count)}"
                arguments.append(String(describing: value))
            }
        }
    }

    static func text(_ message: Message, language: Language = currentLanguage) -> String {
        let template = language == .simplifiedChinese
            ? simplifiedChinese[message.template] ?? message.template
            : message.template
        guard !message.arguments.isEmpty else { return template }
        // Match before substitution: a nickname containing "{1}" must not itself
        // become a format string when another argument is inserted.
        let pattern = try! NSRegularExpression(pattern: #"\{([0-9]+)\}"#)
        let matches = pattern.matches(in: template, range: NSRange(template.startIndex..., in: template))
        let result = NSMutableString(string: template)
        for match in matches.reversed() {
            let index = Int((template as NSString).substring(with: match.range(at: 1)))!
            if message.arguments.indices.contains(index) {
                result.replaceCharacters(in: match.range, with: message.arguments[index])
            }
        }
        return result as String
    }

    /// For static data generated by verify/gen_decor.py and internal shop category keys.
    static func lookup(_ korean: String, language: Language = currentLanguage) -> String {
        language == .simplifiedChinese ? simplifiedChinese[korean] ?? korean : korean
    }
}
